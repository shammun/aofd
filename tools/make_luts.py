"""Write ``assets/luts.json``: 256-entry RGB colour tables for the 3-D kit (``Viz3D.lut(name)``) and the legends.

Perceptually uniform tables only (cmocean: Thyng et al. 2016, MIT licence; matplotlib viridis/cividis, CC0), plus
``jet`` — kept **only** as the labelled bad example of Chapter 0 (``viz:badexample``; ``tools/viz_lint.py`` bans it
everywhere else). Each table is 256×3 bytes, base64-encoded (1 kB each), so the file stays small enough to inline.

Usage::  .venv/Scripts/python.exe tools/make_luts.py            (deterministic: same versions → same bytes)
"""
from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "luts.json"

CMOCEAN = ["thermal", "haline", "dense", "deep", "speed", "balance", "curl", "delta", "amp", "matter"]
MPL = ["viridis", "cividis"]
DIVERGING = {"balance", "curl", "delta"}
BAD = ["jet"]


def table(cmap) -> str:
    rgb = (np.asarray(cmap(np.linspace(0.0, 1.0, 256)))[:, :3] * 255.0 + 0.5).astype(np.uint8)
    return base64.b64encode(rgb.tobytes()).decode("ascii")


def build() -> dict:
    import cmocean
    import matplotlib

    out = {"_about": ("256x RGB uint8 colour tables, base64. cmocean (Thyng et al. 2016, MIT) "
                      f"v{cmocean.__version__}; matplotlib {matplotlib.__version__} viridis/cividis (CC0). "
                      "'jet' is ONLY for the labelled bad example (viz:badexample). Generated by tools/make_luts.py."),
           "_diverging": sorted(DIVERGING), "_bad": BAD, "tables": {}}
    for name in CMOCEAN:
        out["tables"][f"cmocean.{name}"] = table(getattr(cmocean.cm, name))
    for name in MPL + BAD:
        out["tables"][name] = table(matplotlib.colormaps[name])
    return out


def main() -> int:
    data = build()
    OUT.write_text(json.dumps(data, indent=0, sort_keys=True), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {len(data['tables'])} tables, {OUT.stat().st_size / 1e3:.1f} kB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
